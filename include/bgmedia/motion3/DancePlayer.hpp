#pragma once

// DancePlayer: the application-facing facade of BG Motion 3.0.
//
// Owns the clip library and the DanceDirector and implements the two user
// modes. It is deliberately free of rendering, windows and clocks: the host
// passes the media time (BG Sync position, or the Motion Lab clock) into
// update() and gets back the pose for that exact time.

#include "bgmedia/motion3/ClipFootwork.hpp"
#include "bgmedia/motion3/DanceDirector.hpp"
#include "bgmedia/motion3/MotionPrimitive.hpp"
#include "bgmedia/motion3/ProceduralChoreography.hpp"

#include <array>
#include <cstdint>
#include <filesystem>
#include <map>
#include <string>
#include <tuple>
#include <unordered_map>
#include <utility>
#include <vector>

namespace bgmedia::motion {

enum class OverlayMode : std::uint8_t {
    Off,
    Light,
    Full,
    HandsOnly
};

[[nodiscard]] const char* overlayModeName(OverlayMode mode);

// Host-facing persistence for the BG Motion 3.2 controls. It is deliberately
// separate from WarpProfile: the musical warp is engine semantics, while layer
// and spring preferences belong to the desktop host.
struct Motion32Profile {
    OverlayMode overlayMode = OverlayMode::Full;
    bool springEnabled = true;
    float springIntensity = 1.1f;
    float springDamping = 0.5f;
};

[[nodiscard]] bool saveMotion32Profile(const std::filesystem::path& path,
                                       const Motion32Profile& profile,
                                       std::string* error = nullptr);
[[nodiscard]] bool loadMotion32Profile(const std::filesystem::path& path,
                                       Motion32Profile& profile,
                                       std::string* error = nullptr);

class DancePlayer {
public:
    DancePlayer() : director_(&library_) {}
    DancePlayer(const DancePlayer&) = delete;
    DancePlayer& operator=(const DancePlayer&) = delete;

    // Loads every clip of a directory and installs the three procedural
    // showcase dances generated by BG Motion 3.2.
    std::size_t loadLibrary(const std::filesystem::path& directory);
    [[nodiscard]] const DanceLibrary& library() const { return library_; }

    // BG Motion 3.2 footwork pre-pass for the AUTHORED clips of the directory: the
    // library holds re-planned copies (legs never pass through each other); the authored
    // data is kept untouched and re-planned whenever the leg geometry changes (a model
    // was loaded). Generated dances are not touched. Call after loadLibrary.
    void setLegGeometry(const LegGeometry& geometry);
    void setFootworkPlanning(bool enabled);
    void setFootworkGap(float gapCm);  // required leg clearance of the pre-pass (default 2.5 cm)
    [[nodiscard]] bool footworkPlanning() const { return footworkPlan_; }
    [[nodiscard]] const HumanoidClip* authoredClip(const std::string& clipId) const;
    [[nodiscard]] const FootworkPlanReport* footworkReport(const std::string& clipId) const;
    [[nodiscard]] bool ready() const { return !library_.empty(); }

    // BG Motion 3.2 motion layer. Full = torso/head/arms/hands plus safe
    // footwork; Light = torso/head/hands; HandsOnly = hand layer; Off = base.
    void setOverlayMode(OverlayMode mode);
    [[nodiscard]] OverlayMode overlayMode() const { return overlayMode_; }
    void setOverlaySeed(std::uint32_t seed) {
        overlaySeed_ = seed;
        overlays_.clear();  // cached cue sets were planned from the old seed
    }
    [[nodiscard]] std::uint32_t overlaySeed() const { return overlaySeed_; }
    // Overlay cues of one clip for one loop (loop = floor(clipBeat / beats)). Authored clips get
    // their own cue set per loop, planned from (seed, clip id, loop), so repeated loops do not
    // repeat the same gestures. Generated dances keep their generator's cues.
    [[nodiscard]] const std::vector<PrimitiveCue>& overlaysFor(const std::string& clipId,
                                                               std::int64_t loop);
    [[nodiscard]] const std::vector<PrimitiveCue>& overlaysFor(const std::string& clipId);
    // Overlay cue of the schedule between two media times, with the media time it starts at.
    // Diagnostics and tests: the composition uses the same plans, per segment and loop.
    struct PlannedOverlay {
        double mediaTime = 0.0;
        std::string clipId;
        PrimitiveKind kind = PrimitiveKind::HandFlick;
        float intensity = 0.0f;
        std::string reason;
    };
    [[nodiscard]] std::vector<PlannedOverlay> plannedOverlays(double fromTime, double toTime);
    [[nodiscard]] const std::vector<GeneratedDance>& generatedDances() const {
        return generated_;
    }
    [[nodiscard]] bool selectClip(const std::string& clipId, double now, bool immediate = false);

    // The musical grid driving the clips. Rebases the running clip so the pose
    // does not jump when the tempo changes.
    void setGrid(BeatClock clock, double now);
    // Installs a full musical timeline (meter confidence, real accents, bass).
    void setMusicalTimeline(MusicalTimeline timeline, double now);
    // BG Beat analysis used by Auto mode and for the accent/timeline map.
    // nullptr = no music. `now` keeps a Manual dance phase stable.
    void setAnalysis(const AnalysisResult* analysis);
    void setAnalysis(const AnalysisResult* analysis, double now);

    void setMode(DanceMode mode, double now);
    [[nodiscard]] DanceMode mode() const { return mode_; }

    // Expressive musical warp. Off / Soft / Expressive; the value is also
    // persisted by the desktop host, not by the engine.
    void setExpression(MotionExpression expression) { director_.setExpression(expression); }
    [[nodiscard]] MotionExpression expression() const { return director_.expression(); }
    void setWarpProfile(WarpProfile profile) { director_.setWarpProfile(profile); }
    [[nodiscard]] const WarpProfile& warpProfile() const { return director_.warpProfile(); }
    [[nodiscard]] const MusicalTimeline& timeline() const { return director_.timeline(); }

    // Manual selection (switches to Manual). The change lands on the next beat.
    void select(DanceStyle style, double now, bool immediate = false);
    void setOneShot(bool oneShot) { oneShot_ = oneShot; }
    [[nodiscard]] bool oneShot() const { return oneShot_; }
    // Groove -> Hip-Hop -> Side Step -> Energetic -> Idle showcase.
    void startTestDance(double now);
    void startSequence(const std::vector<DanceStyle>& styles, double now, double beatsPerStyle,
                       bool immediate = false);

    // Pose for `mediaTime`. Detects seeks (backward or large jumps) and
    // realigns the Manual schedule; Auto is a pure plan and needs nothing.
    [[nodiscard]] DanceFrame update(double mediaTime);

    [[nodiscard]] const DanceDirector& director() const { return director_; }
    [[nodiscard]] DanceStyle selectedStyle() const { return director_.selectedStyle(); }
    [[nodiscard]] const std::string& autoNote() const { return autoNote_; }

private:
    void replanAuthored();
    // Overlay cues of one schedule segment for one loop of its clip (the loop index comes from
    // the segment's linear clip beat). With an analysed timeline the cues are planned from the
    // track's events mapped through this segment; otherwise they are the grid plan of overlaysFor.
    [[nodiscard]] const std::vector<PrimitiveCue>& segmentOverlays(const ScheduleSegment& segment,
                                                                  std::int64_t loop);
    // Stateful hand-over from the last output pose (BG Motion 3.3, A3/A4). The schedule
    // stays a pure function of media time; only this blend remembers where it started.
    // Its progress is media time travelled, so it works for a paused or scrubbed host too.
    void armBlend(double seconds, bool carryFeet = false);
    void armIfMoved(const BeatClock& before, const BeatClock& after, double now);
    void advanceBlend(double travelled);
    [[nodiscard]] DanceFrame sampleFrame(double mediaTime);
    void applyBlend(DanceFrame& frame);
    void advanceFootCarry(double travelled);
    void applyFootCarry(DanceFrame& frame);

    struct PoseBlend {
        bool active = false;
        bool hold = false;     // armed since the last frame: that frame shows the outgoing pose
        ClipPose from;
        double progress = 0.0; // media seconds travelled since the blend was armed
        double seconds = 0.0;
    };
    PoseBlend blend_;
    // A plan or grid blend must not slide planted feet: their offset from the new
    // schedule is carried and paid off while the schedule swings that foot (plus a slow
    // fallback while it stays planted), not over the body blend.
    struct FootCarry {
        bool pending = false;  // capture the offset on the next applied frame
        std::array<Vec3, 2> offset{};
        std::array<float, 2> yaw{};
        std::array<double, 2> remaining{0.0, 0.0};
        std::array<float, 2> contact{1.0f, 1.0f};  // schedule contact of the last frame
    };
    FootCarry carry_;
    bool haveLastPose_ = false;
    bool lastJump_ = false;
    ClipPose lastPose_;

    DanceLibrary library_;
    std::vector<HumanoidClip> authored_;
    std::map<std::string, FootworkPlanReport> footworkReports_;
    LegGeometry legGeometry_;
    bool footworkPlan_ = true;
    float footworkGapCm_ = 2.5f;
    DanceDirector director_;
    DanceMode mode_ = DanceMode::Manual;
    const AnalysisResult* analysis_ = nullptr;
    bool oneShot_ = false;
    double lastTime_ = -1.0e9;
    std::string autoNote_;
    OverlayMode overlayMode_ = OverlayMode::Full;
    std::uint32_t overlaySeed_ = 3u;
    std::vector<GeneratedDance> generated_;
    // Overlay plans: a pure memo of the planners, bounded in size. The grid plan depends on the
    // clip and the loop; a musical plan also on the segment's alignment. Musical plans depend on
    // the timeline too, so the memo is dropped whenever the timeline changes.
    struct OverlayPlanKey {
        std::string clipId;
        std::int64_t loop = 0;
        bool musical = false;
        double alignTime = 0.0;
        double entryClipBeat = 0.0;
        double rate = 0.0;
        bool phraseHit = false;
        bool operator<(const OverlayPlanKey& other) const {
            return std::tie(clipId, loop, musical, alignTime, entryClipBeat, rate, phraseHit) <
                   std::tie(other.clipId, other.loop, other.musical, other.alignTime,
                            other.entryClipBeat, other.rate, other.phraseHit);
        }
    };
    std::map<OverlayPlanKey, std::vector<PrimitiveCue>> overlays_;
    std::unordered_map<std::string, std::vector<PrimitiveCue>> generatedOverlays_;
};

} // namespace bgmedia::motion
